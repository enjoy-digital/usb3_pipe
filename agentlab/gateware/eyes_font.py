# Font ---------------------------------------------------------------------------------------------

EYES_FONT_WIDTH  = 8
EYES_FONT_HEIGHT = 16

def eyes_font():
    """Font bitmap: 256*16 bytes (glyph c, line l at c*16 + l, bit 7: leftmost pixel)."""
    return [int(line[2*i:2*i + 2], 16) for line in _EYES_FONT_DATA.split() for i in range(16)]

def eyes_char_code(char):
    """Font code of a Unicode character (unsupported: "?")."""
    u = ord(char)
    if 0x20 <= u <= 0x7e or 0xa0 <= u <= 0xff:
        return u
    if u in EYES_FONT_EXTRA:
        return 0x80 + EYES_FONT_EXTRA.index(u)
    return ord("?")
