    text(890, 156, "USB3 Device Core", 18, weight="bold")
    text(890, 176, "usb3_core", 13, style="italic")
    box(814, 190, 966, 254, fill=KEY, lines=[("Link Layer", 16, "bold"), ("HP/LC/DPP · CRCs", 13), ("flow control · retries", 13)])
