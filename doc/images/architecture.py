    box(1020, 342, 1165, 406, lines=[("CDC-ACM", 16, "bold"), ("serial port", 13), ("LiteX UART PHY", 13)])
    box(1020, 418, 1165, 482, lines=[("Mass Storage", 16, "bold"), ("Bulk-Only · SCSI", 13), ("RAM/DRAM disk", 13)])
