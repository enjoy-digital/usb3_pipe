"""Fake AgentLab backends (CSR bus, serial ports, events endpoint) for host software tests."""

from agentlab.host import constants as c
from agentlab.host.csr        import CSRMap, CSRs
from agentlab.host.uart       import DUTUart
from agentlab.host.events     import Event, pack_event
from agentlab.host.instrument import Instrument

SYS_CLK_FREQ = 125e6

# CSR Map ------------------------------------------------------------------------------------------

CSR_REGISTERS = [
    # name,                  size, mode.
    (c.CSR_TIMESTAMP,          2, "ro"),
    (c.CSR_TIMESTAMP_LATCH,    1, "wo"),
    (c.CSR_MARKER,             1, "wo"),
    (c.CSR_POWER_OUT,          1, "rw"),
    (c.CSR_GPIO_OE,            1, "rw"),
    (c.CSR_GPIO_OUT,           1, "rw"),
    (c.CSR_GPIO_IN,            1, "ro"),
    (c.CSR_GPIO_EDGE_MASK,     1, "rw"),
    (c.csr_uart_baudrate(0),   1, "rw"),
]

def csr_csv(base=0xf0000000):
    lines = [
        "#" + "-"*40,
        "# Auto-generated by LiteX",
        "#" + "-"*40,
        "csr_base,agentlab,0x{:08x},,".format(base),
    ]
    addr = base
    for name, size, mode in CSR_REGISTERS:
        lines.append("csr_register,{},0x{:08x},{},{}".format(name, addr, size, mode))
        addr += 4*size
    lines.append("constant,config_clock_frequency,{},,".format(int(SYS_CLK_FREQ)))
    lines.append("constant,config_csr_data_width,32,,")
    lines.append("memory_region,csr,0x{:08x},65536,io".format(base))
    return "\n".join(lines) + "\n"

# Fake Clock ---------------------------------------------------------------------------------------

class FakeClock:
    def __init__(self):
        self.now = 0.0

    def __call__(self):
        return self.now

    def sleep(self, t):
        self.now += t

# Fake CSR Bus -------------------------------------------------------------------------------------

class FakeCSRBus:
    """Word-addressed memory with a write log and hooks emulating the AgentLab CSRs."""
    def __init__(self, csr_map: CSRMap, clock=None):
        self.csr_map = csr_map
        self.clock   = clock or FakeClock()
        self.mem     = {}
        self.log     = [] # (time, name, value) of CSR writes.
        self.names   = {r.addr: r.name for r in csr_map.registers.values()}

    def ticks(self):
        return int(self.clock()*SYS_CLK_FREQ)

    def read(self, addr, length=1):
        reg = self.csr_map.registers.get(self.names.get(addr, ""), None)
        if reg is not None and reg.name == c.CSR_TIMESTAMP:
            t = self.ticks()
            return [(t >> 32) & 0xffffffff, t & 0xffffffff]
        if reg is not None and reg.name == c.CSR_GPIO_IN:
            # Loopback: outputs driven when enabled, inputs pulled-up otherwise.
            oe  = self.mem.get(self.csr_map[c.CSR_GPIO_OE].addr, 0)
            out = self.mem.get(self.csr_map[c.CSR_GPIO_OUT].addr, 0)
            return [(out & oe) | (~oe & 0xffffffff)]
        return [self.mem.get(addr + 4*i, 0) for i in range(length)]

    def write(self, addr, datas):
        for i, d in enumerate(datas):
            self.mem[addr + 4*i] = d
        name = self.names.get(addr, "0x{:08x}".format(addr))
        self.log.append((self.clock(), name, datas[0] if len(datas) == 1 else datas))

    def close(self):
        pass

# Fake Serial --------------------------------------------------------------------------------------

class FakeSerial:
    """pyserial-like port: RX chunks delivered at scheduled (fake clock) times."""
    def __init__(self, clock=None, chunks=None, read_time=0.05):
        self.clock     = clock or FakeClock()
        self.chunks    = list(chunks or []) # [(time, bytes)].
        self.read_time = read_time
        self.rx        = b""
        self.tx        = b""
        self.baudrate  = 115200
        self.closed    = False

    def feed(self, data, at=None):
        self.chunks.append((self.clock() if at is None else at, data))

    def _deliver(self):
        for chunk in [ch for ch in self.chunks if ch[0] <= self.clock()]:
            self.rx += chunk[1]
            self.chunks.remove(chunk)

    @property
    def in_waiting(self):
        self._deliver()
        return len(self.rx)

    def read(self, size=1):
        self._deliver()
        if not self.rx:
            self.clock.sleep(self.read_time) # Serial timeout.
            self._deliver()
        data, self.rx = self.rx[:size], self.rx[size:]
        return data

    def write(self, data):
        self.tx += bytes(data)
        return len(data)

    def flush(self):
        pass

    def reset_input_buffer(self):
        self._deliver()
        self.rx = b""

    def close(self):
        self.closed = True

# Fake UARTBone Port -------------------------------------------------------------------------------

class FakeUARTBonePort:
    """Serial port emulating the gateware Stream2Wishbone (word memory behind it)."""
    def __init__(self):
        self.mem    = {}
        self.rx     = b""
        self.frames = []

    def write(self, data):
        data = bytes(data)
        self.frames.append(data)
        cmd, length, addr = data[0], data[1], int.from_bytes(data[2:6], "big")
        if cmd == 0x01:
            for i in range(length):
                self.mem[addr + i] = int.from_bytes(data[6 + 4*i:10 + 4*i], "big")
        elif cmd == 0x02:
            for i in range(length):
                self.rx += self.mem.get(addr + i, 0).to_bytes(4, "big")
        return len(data)

    def read(self, size):
        data, self.rx = self.rx[:size], self.rx[size:]
        return data

    def reset_input_buffer(self):
        self.rx = b""

    def close(self):
        pass

# Fake Events Endpoint -----------------------------------------------------------------------------

class FakeEventsEndpoint:
    """Events bulk endpoint: returns queued transfers (arbitrary split), then timeouts."""
    def __init__(self, transfers=None):
        self.transfers = list(transfers or [])

    def push_events(self, events, split=None):
        data = b"".join(pack_event(e) for e in events)
        if split is None:
            self.transfers.append(data)
        else:
            self.transfers += [data[i:i + split] for i in range(0, len(data), split)]

    def __call__(self, size, timeout_ms):
        if self.transfers:
            return self.transfers.pop(0)
        return b""

# Fake Instrument ----------------------------------------------------------------------------------

def uart_events(text, source=0, t0=0, dt=1000, typ=c.EVENT_UART_RX):
    return [Event(typ, source, b, t0 + i*dt) for i, b in enumerate(text.encode())]

def make_instrument(uart_chunks=None, events=None):
    """Instrument on fake backends; returns (instrument, fakes dict)."""
    clock   = FakeClock()
    csr_map = CSRMap.from_csv(csr_csv())
    bus     = FakeCSRBus(csr_map, clock)
    ports   = {}
    def uart_factory(index):
        ports[index] = FakeSerial(clock, (uart_chunks or {}).get(index, []))
        return DUTUart(ports[index], index=index, clock=clock)
    endpoint = FakeEventsEndpoint()
    if events:
        endpoint.push_events(events)
    instrument = Instrument(csrs=CSRs(bus, csr_map), uart_factory=uart_factory,
        events_read=endpoint, sleep=clock.sleep)
    return instrument, {"clock": clock, "bus": bus, "ports": ports, "endpoint": endpoint}
