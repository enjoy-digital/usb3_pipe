"""USB3 Link Training and Status State Machine (USB 3.2 7.5): Polling, U0, Recovery, U1/U2/U3,
Hot/Warm Reset, Compliance, Loopback, eSS.Inactive, PM handshake and timers, and the SuperSpeedPlus
Polling substates (SSPPolling, 7.5.4.3-7.5.4.6, see doc/gen2-x2-roadmap.md).
"""

from migen import *
from migen.genlib.misc import WaitTimer

from litex.gen import *

from usb3_pipe.common import LTSSM_PIPE_INTERFACE
from usb3_pipe.lfps import (U1ExitLFPSBurst, U2ExitLFPSBurst, U3WakeupLFPSBurst,
    exit_burst_cycles,
    exit_u1_min_cycles, exit_u2_min_cycles, exit_u3_min_cycles)
from usb3_pipe.lfps import (LFPSRXFrontEnd, SCDGenerator, SCDChecker, LBPMGenerator, LBPMChecker,
    LBPM_PHY_CAPABILITY, LBPM_PHY_READY, lbpm_phy_capability, rounded_cycles)

# Link Training and Status State Machine -----------------------------------------------------------

# USB 3.2 Rev 1.1 references (PDF page = printed page + 31):
# - Section 7.5   (LTSSM states, PDF p190-p236): Polling.Idle p214-217, U1 p220-222, U2 p223,
#   U3 p224, Compliance p218-219, Loopback p229-232, Hot Reset p233-235, Recovery p226-229,
#   SS.Inactive p191 (Table 7-12 timeouts).
# - Section 7.2.4.2 (Link Power Management, PDF p173-177): LGO_Ux/LAU/LXU/LPMA handshake and
#   PM_LC_TIMER (4us) / PM_ENTRY_TIMER (8us) / Ux_EXIT_TIMER (6ms) / U1_MIN_RESIDENCY (3us).
# - Section 6.9   (LFPS, PDF p130-134): Table 6-30 patterns, Table 6-31 handshake timings.
# Simplifications:
# - Rx.Detect family is not modelled (Polling.ExitToRxDetect is a transient state towards
#   Polling.Entry, i.e. instant re-training).
# - TS2 Reset/Loopback bits and the Idle Symbol handshake are decoded/generated by the PIPE
#   (ts_rx_ts2_* / ts_tx_ts2_* / idle_handshake / idle_handshake_done, LTSSM_PIPE_INTERFACE).
# - 20ns gap rule / electrical parameters are not modelled. Concurrent U1 exit is modelled
#   (both partners send a full 900ns burst).
# - U3 DS failure retry limited to 2 retries then eSS.Inactive.

@ResetInserter()
class USB3LTSSM(LiteXModule):
    """Link Training and Status State Machine (7.5)."""
    def __init__(self, sys_clk_freq, with_timers=True, timer_scale=1, ssp=False):
        # Status -----------------------------------------------------------------------------------
        # (rx_ready/tx_ready: PIPE interface below).
        self.u0                 = Signal()
        self.recovery           = Signal()
        self.exit_to_compliance = Signal()
        self.exit_to_rx_detect  = Signal()
        self.u1                 = Signal()
        self.u2                 = Signal()
        self.u3                 = Signal()
        self.compliance         = Signal()
        self.loopback           = Signal()
        self.hot_reset          = Signal()
        self.ess_inactive       = Signal()
        self.polling_idle       = Signal()

        # PIPE interface (LTSSM_PIPE_INTERFACE, connected by USB3PHY) ------------------------------
        # idle_handshake_done reset=1: short path for a standalone LTSSM.
        for name, width, direction in LTSSM_PIPE_INTERFACE:
            setattr(self, name, Signal(width, name=name, reset=int(name == "idle_handshake_done")))

        # Role & enables (7.5) ---------------------------------------------------------------------
        self.ds_port           = Signal(reset=0) # i: 1 = DS/host role, 0 = UFP/device role
        self.compliance_enable = Signal(reset=0) # i: DS Compliance migration path enable (7.5.4.3)

        # PM handshake interface (7.2.4.2, LCMD transport owned by the Link Layer) -----------------
        self.lgo_u1 = Signal() # i: partner LGO_U1 decoded (pulse)
        self.lgo_u2 = Signal() # i: partner LGO_U2 decoded (pulse)
        self.lgo_u3 = Signal() # i: partner LGO_U3 decoded (pulse)
        self.lau    = Signal() # i: our LGO_Ux accepted (LAU received)
        self.lxu    = Signal() # i: our LGO_Ux rejected (LXU received) -> stay in U0
        self.lpma   = Signal() # i: partner LPMA received (pulse): accepted Ux entered without
                               #    waiting for the PM_ENTRY_TIMER timeout (7.2.4.2.3)
        self.req_u1 = Signal() # i: upper layer wants U1
        self.req_u2 = Signal() # i: upper layer wants U2
        self.req_u3 = Signal() # i: upper layer wants U3 (DS only)

        self.tx_lgo_u1 = Signal() # o: pulse, Link Layer should send LGO_U1
        self.tx_lgo_u2 = Signal() # o
        self.tx_lgo_u3 = Signal() # o
        self.tx_lau    = Signal() # o: pulse, Link Layer should send LAU (accept)
        self.tx_lxu    = Signal() # o: pulse, Link Layer should send LXU (reject)
        self.tx_lpma   = Signal() # o: pulse, Link Layer should send LPMA (ack-ack)

        # Link activity (tU0RecoveryTimeout trigger, 7.5.6.2) --------------------------------------
        self.link_activity = Signal(reset=1) # i: 1 when link active in current <1ms window

        # Upper layer directs (7.5) ----------------------------------------------------------------
        self.directed_recovery = Signal()        # i: directed to Recovery
        self.directed_loopback = Signal()        # i: directed as Loopback master
        self.loopback_capable  = Signal(reset=0) # i: loopback master capability
        self.hot_reset_req     = Signal()        # i: DS directed PORT_RESET (Hot Reset)
        self.warm_reset_req    = Signal()        # i: DS directed BH_PORT_RESET (Warm Reset LFPS)
        self.exit_u1_req       = Signal()        # i: initiate U1 exit (upper layer/traffic)
        self.exit_u2_req       = Signal()        # i: initiate U2 exit
        self.wakeup_u3_req     = Signal()        # i: initiate U3 wakeup (DS, or UFP remote wakeup)

        # U2 inactivity (PORT_U2_TIMEOUT LMP, 0 = disabled, 7.5.7.2) -------------------------------
        self.u2_timeout = Signal(8) # i: U2 Inactivity Timeout (LMP 8.4.3, Table 10-17: 256us units,
                                    #    00h/FFh: disabled), U1 -> U2 on timeout (10.6.2.4).

        # SuperSpeedPlus Polling (ssp=True, SSPPolling below, 7.5.4.3-7.5.4.6) ---------------------
        # In Polling.LFPS, ssp_polling runs the SSPPolling substates (SCD1/SCD2, LBPM PortMatch/
        # PortConfig) instead of the SuperSpeed Polling.LFPS handshake: ssp_done exits to
        # Polling.RxEQ, ssp_fallback (SuperSpeed partner) continues with the SuperSpeed handshake.
        self.ssp_polling  = Signal() # o
        self.ssp_done     = Signal() # i
        self.ssp_fallback = Signal() # i

        # Compliance testability (7.5.4.3) ---------------------------------------------------------
        self.compliance_ping_count = Signal(16) # o: Ping.LFPS received count in Compliance

        # # #

        # Timer scaling: all timeouts divided by timer_scale (sim acceleration), specification
        # exact values for timer_scale=1.
        scaled = lambda t: max(1, int(t*sys_clk_freq)//timer_scale)

        tx_lfps_count   = Signal(16)
        rx_lfps_seen    = Signal()
        polling_lfps_ok = Signal() # Polling.LFPS handshake completed since power-on/Warm Reset.
        rx_ts1_seen     = Signal()
        rx_ts1_inv_seen = Signal()
        rx_ts2_seen     = Signal()
        ts2_tx_after    = Signal() # current TS2 burst started after the 8 consecutive TS2 received
        rx_lb_seen      = Signal() # partner TS2 Loopback bit latched during training/recovery
        lb_pending      = Signal() # directed loopback via Recovery (TS2 Loopback bit)
        loopback_master = Signal() # Loopback role
        hr_seen         = Signal() # partner TS2 Reset bit seen in HotReset.Active
        hr_tx_reset     = Signal() # TS2 Reset bit transmitted in HotReset.Active.

        # Timers (Table 7-12 LTSSM timeouts, 7.2.4.2 Link Power Management timers) -----------------
        # tPollingLFPSTimeout (360ms, Polling.LFPS).
        self.t_polling_lfps = t_polling_lfps = WaitTimer(scaled(360e-3))
        # tPollingActiveTimeout/tRecoveryActiveTimeout/tHotResetActiveTimeout (12ms): shared by
        # Polling.Active, Recovery.Active and HotReset.Active (never consecutive states).
        self.t_active = t_active = WaitTimer(scaled(12e-3))
        # tPollingConfigurationTimeout (12ms, Polling.Configuration).
        self.t_polling_config = t_polling_config = WaitTimer(scaled(12e-3))
        # tRecoveryConfigurationTimeout (6ms, Recovery.Configuration).
        self.t_recovery_config = t_recovery_config = WaitTimer(scaled(6e-3))
        # tPollingIdleTimeout (2ms, Polling.Idle).
        self.t_polling_idle = t_polling_idle = WaitTimer(scaled(2e-3))
        # tU0RecoveryTimeout (1ms without link activity in U0, 7.5.6.2).
        self.t_u0_recovery = t_u0_recovery = WaitTimer(scaled(1e-3))
        # tRecoveryIdleTimeout (2ms, Recovery.Idle).
        self.t_recovery_idle = t_recovery_idle = WaitTimer(scaled(2e-3))
        # tHotResetExitTimeout (2ms, HotReset.Exit).
        self.t_hot_reset_exit = t_hot_reset_exit = WaitTimer(scaled(2e-3))
        # Ux_EXIT_TIMER (6ms, 7.2.4.2.1).
        self.t_ux_exit = t_ux_exit = WaitTimer(scaled(6e-3))
        # PM_LC_TIMER (4us, 7.2.4.2.3).
        self.t_pm_lc = t_pm_lc = WaitTimer(scaled(4e-6))
        # PM_ENTRY_TIMER (8us, 7.2.4.2.3).
        self.t_pm_entry = t_pm_entry = WaitTimer(scaled(8e-6))
        # teSSInactiveQuietTimeout (12ms, eSS.Inactive).
        self.t_ess_quiet = t_ess_quiet = WaitTimer(scaled(12e-3))
        # tU3WakeupRetryDelay (100ms, 7.2.4.2.7).
        self.t_u3_retry = t_u3_retry = WaitTimer(scaled(100e-3))
        # Transient Rx.Detect equivalent (Polling.ExitToRxDetect, Rx.Detect not modelled).
        self.t_rx_detect = t_rx_detect = WaitTimer(max(1, 64//timer_scale))

        # LFPS Exit Handshake (6.9.2, shared by U1/U2/Loopback exit and U3 wakeup) -----------------
        # Modes: 0=none, 1=U1 exit, 2=U2/Loopback exit, 3=U3 wakeup.
        # Each partner sends at least its minimum burst and keeps transmitting until the partner
        # burst is seen (concurrent-safe): success = own minimum burst completed and partner burst
        # seen; failure = tNoLFPSResponseTimeout (2ms, 2ms, 10ms) without success.
        # Burst lengths share the same source as the partner burst-checker detection windows
        # (usb3_pipe.lfps helpers): burst = max(scaled typ, detect_min + RX_DETECT_LATENCY), so the
        # responder still sees the initiator burst in flight at any timer_scale (Table 6-31 order
        # preserved). The tNoLFPSResponse guard (2ms/2ms/10ms) is >= the responder's own burst +
        # detection latency.
        hs_guard     = [0, scaled(2e-3), scaled(2e-3), scaled(10e-3)] # tNoLFPSResponseTimeout.
        hs_mode      = Signal(2)
        hs_run       = Signal()
        hs_send      = Signal() # burst ongoing
        hs_rx        = Signal() # partner burst seen
        hs_cnt       = Signal(max=max(hs_guard) + 1) # <= hs_gcnt.
        hs_gcnt      = Signal(max=max(hs_guard) + 1) # hs_run ends at the guard.
        hs_done_ok   = Signal() # pulse
        hs_done_err  = Signal() # pulse

        hs_burst_len = Array([0,
            exit_burst_cycles(sys_clk_freq, timer_scale, U1ExitLFPSBurst,
                              exit_u1_min_cycles(sys_clk_freq, timer_scale)),
            exit_burst_cycles(sys_clk_freq, timer_scale, U2ExitLFPSBurst,
                              exit_u2_min_cycles(sys_clk_freq, timer_scale)),
            exit_burst_cycles(sys_clk_freq, timer_scale, U3WakeupLFPSBurst,
                              exit_u3_min_cycles(sys_clk_freq, timer_scale)),
        ])
        hs_guard_len = Array(hs_guard)
        hs_rx_pulse  = Array([0,
            self.lfps_rx_exit_u1,
            self.lfps_rx_exit_u2,
            self.lfps_rx_wakeup_u3,
        ])

        self.sync += [
            hs_done_ok.eq(0),
            hs_done_err.eq(0),
            If(hs_run,
                hs_gcnt.eq(hs_gcnt + 1),
                If(hs_send,
                    hs_cnt.eq(hs_cnt + 1),
                    # Minimum burst transmitted and partner LFPS seen: LFPS transmission continues
                    # until the handshake is declared successful (6.9.2).
                    If(((hs_cnt + 1) >= hs_burst_len[hs_mode]) & (hs_rx | hs_rx_pulse[hs_mode]),
                        hs_send.eq(0)
                    )
                ),
                If(hs_rx_pulse[hs_mode],
                    hs_rx.eq(1)
                ),
                If(hs_rx & ~hs_send,
                    hs_done_ok.eq(1),
                    hs_run.eq(0),
                ).Elif((hs_gcnt + 1) >= hs_guard_len[hs_mode],
                    hs_done_err.eq(1),
                    hs_run.eq(0),
                )
            ).Else(
                hs_cnt.eq(0),
                hs_gcnt.eq(0),
                hs_rx.eq(0),
                hs_send.eq(0),
            )
        ]

        # Warm Reset burst (6.9: DS only originator, UFP responds until DS stops) ------------------
        wr_run  = Signal() # Warm Reset burst ongoing
        wr_orig = Signal() # 1 = originator (DS), 0 = responder (UFP)
        wr_rx   = Signal()
        wr_cnt  = Signal(max=scaled(100e-3) + 1) # wr_run ends at tReset.
        wr_gcnt = Signal(max=scaled(200e-3) + 1) # wr_run ends at the guard.
        wr_done = Signal() # pulse: burst phase finished

        self.sync += [
            wr_done.eq(0),
            If(wr_run,
                If(wr_orig,
                    wr_cnt.eq(wr_cnt + 1),
                    If((wr_cnt + 1) >= scaled(100e-3), # tReset typ 100ms (80-120ms)
                        wr_done.eq(1),
                        wr_run.eq(0)
                    )
                ).Else(
                    If(self.lfps_rx_reset,
                        wr_rx.eq(1)
                    ),
                    wr_gcnt.eq(wr_gcnt + 1),
                    If(wr_rx & ~self.lfps_rx_reset,      # DS stopped -> stop responding
                        wr_done.eq(1),
                        wr_run.eq(0)
                    ).Elif((wr_gcnt + 1) >= scaled(200e-3), # guard (max burst 120ms)
                        wr_done.eq(1),
                        wr_run.eq(0)
                    )
                )
            ).Else(
                wr_cnt.eq(0),
                wr_gcnt.eq(0),
                wr_rx.eq(0),
            )
        ]

        # U1 DS Ping timeout counter (tU1PingTimeout 300ms, reset on Ping reception, 7.5.7.2) ------
        u1_ping_lim  = scaled(300e-3)
        u1_ping_cnt  = Signal(max=u1_ping_lim + 1)
        u1_ping_done = u1_ping_cnt >= u1_ping_lim

        # U1 UFP min residency (U1_MIN_RESIDENCY 3us, 7.2.4.2.7) -----------------------------------
        u1_res_lim        = scaled(3e-6)
        u1_res_cnt        = Signal(max=u1_res_lim + 1)
        u1_residency_done = u1_res_cnt >= u1_res_lim

        # U2 Inactivity Timeout counter (u2_timeout x 256us in U1, 10.6.2.4) -----------------------
        u2_tick_lim     = scaled(256e-6)
        u2_tick_cnt     = Signal(max=u2_tick_lim + 1)
        u2_cnt          = Signal(8)
        u2_timeout_done = Signal()
        self.comb += u2_timeout_done.eq((self.u2_timeout != 0x00) & (self.u2_timeout != 0xff) &
            (u2_cnt == self.u2_timeout))

        # Hot Reset Active reset-done delay (US clears Reset bit after own reset) ------------------
        hr_cnt = Signal(16)
        # The Reset=1 TS2 window must outlast the partner's HotReset.Active entry lag (~2 cycles via
        # the TS2 plane at any scale), or the partner never latches hr_seen and both sides fall to
        # the 12ms timeout. 16 cycles gives an 8x margin over that lag at scale>=16; scale=1 keeps
        # the exact 256.
        hr_delay = max(16, 256//timer_scale)

        # U3 wakeup retry (DS, 7.2.4.2.4: 2 retries then eSS.Inactive) -----------------------------
        u3_wakeup_pending = Signal()
        u3_retry_wait     = Signal()
        u3_entry_cnt      = Signal(2) # consecutive U3 entry PM_LC failures (7.2.4.2.4)

        # PM handshake registers (7.2.4.2) ---------------------------------------------------------
        pm_kind          = Signal(2) # requested Ux: 1/2/3
        self.pm_sent_lgo = pm_sent_lgo = Signal()  # LGO sent, LAU/LXU pending (PM_LC_TIMER armed)
        pm_acc_kind      = Signal(2) # partner request accepted (LAU sent)
        pm_conc_kind     = Signal(2) # UFP: DS request received while own LGO pending (7.2.4.2.5)
        pm_lgo_fire  = Signal()
        pm_lau_fire  = Signal()
        pm_lxu_fire  = Signal()
        pm_lpma_fire = Signal()

        # Ux_EXIT_TIMER arming (armed on U1/U2/Loopback exit LFPS, disarmed on U0 entry) -----------
        ux_armed = Signal()

        # FSM --------------------------------------------------------------------------------------
        self.fsm = fsm = FSM(reset_state="Polling.Entry")

        # Transitions shared by several states (lists of statements). The signals are bound as
        # default arguments: a closure would turn the captured __init__ locals into cell variables
        # and break the migen Signal name inference (tracer) of the __init__ locals.
        def goto_recovery(recovery=self.recovery, seen=(rx_ts1_seen, rx_ts1_inv_seen, rx_ts2_seen)):
            # Recovery entry: TS1/TS2 evidence of the previous training attempt cleared.
            return [
                NextValue(recovery, 1),
                *[NextValue(s, 0) for s in seen],
                NextState("Recovery.Active"),
            ]

        def goto_hot_reset(hr_seen=hr_seen):
            return [
                NextValue(hr_seen, 0),
                NextState("HotReset.Active"),
            ]

        def goto_ux(kind):
            # Ux entry for a PM handshake kind (1: U1, 2: U2, 3: U3).
            return [If(kind == 1,
                NextState("U1")
            ).Elif(kind == 2,
                NextState("U2")
            ).Else(
                NextState("U3")
            )]

        def warm_reset(orig, wr_run=wr_run, wr_orig=wr_orig):
            # Warm Reset LFPS burst: orig=1 DS originator, orig=0 UFP responder (6.9).
            return [
                NextValue(wr_run,  1),
                NextValue(wr_orig, orig),
                NextState("WarmReset"),
            ]

        def hs_start(mode, responder=False, hs=(hs_mode, hs_run, hs_send, hs_rx)):
            # LFPS exit/wakeup handshake start (mode: 1 U1, 2 U2/Loopback, 3 U3). A responder
            # starts with hs_rx pre-latched: the qualified partner burst is the request evidence.
            hs_mode, hs_run, hs_send, hs_rx = hs
            return [
                NextValue(hs_mode, mode),
                NextValue(hs_run,  1),
                NextValue(hs_send, 1),
                *([NextValue(hs_rx, 1)] if responder else []),
            ]

        # Partner exit/wakeup LFPS detection (6.9.2, Table 6-31) -----------------------------------
        # The handshake initiator transmits LFPS until the handshake is declared successful or
        # failed: the responder shall respond while the initiator LFPS is still received (t11-t10:
        # 2us max for U1 exit). A detected exit/wakeup burst (U1 >= 300ns, U2/Loopback/U3 >= 80us)
        # is a handshake request as soon as it is detected (except Ping.LFPS, an upstream port
        # proceeds with the handshake even if the LFPS later turns out to be a Warm Reset). The
        # request is only raised while in a handshake-capable state (U1/U2/U3/Loopback) and is
        # consumed by the handshake start (see Partner exit/wakeup request below).
        rx_burst_ok = Signal() # level: partner exit/wakeup burst detected, waits for use

        # Entry State ------------------------------------------------------------------------------
        fsm.act("Polling.Entry",
            self.lfps_tx_idle.eq(1),
            NextValue(tx_lfps_count,  16),
            NextValue(rx_lfps_seen,    0),
            NextValue(rx_ts1_seen,     0),
            NextValue(rx_ts1_inv_seen, 0),
            NextValue(rx_ts2_seen,     0),
            NextValue(rx_lb_seen,      0),
            NextState("Polling.LFPS"),
        )

        # LFPS State (7.5.4.3) ---------------------------------------------------------------------
        polling_lfps = If(t_polling_lfps.done,
            # 360ms timeout: Compliance for UFP (always enabled) and DS when directed
            # (compliance_enable), only if the Polling.LFPS handshake has never been completed
            # since power-on/Warm Reset (7.5.4.3.2: a later timeout is a training failure, not a
            # passive compliance load). Otherwise retry training.
            If(polling_lfps_ok | (self.ds_port & ~self.compliance_enable),
                NextState("Polling.ExitToRxDetect")
            ).Else(
                NextState("Compliance")
            )
        )
        ss_handshake = (self.lfps_tx_count >= tx_lfps_count)
        if ssp:
            polling_lfps = polling_lfps.Elif(self.ssp_done,
                NextValue(polling_lfps_ok, 1),
                NextState("Polling.RxEQ"),
            )
            ss_handshake = self.ssp_fallback & ss_handshake
        polling_lfps = polling_lfps.Elif(ss_handshake,
            If(self.lfps_rx_polling & ~rx_lfps_seen,
                NextValue(rx_lfps_seen, 1),
                NextValue(tx_lfps_count, self.lfps_tx_count + 4)
            ),
            If(rx_lfps_seen,
                NextValue(polling_lfps_ok, 1),
                NextState("Polling.RxEQ"),
            )
        )
        fsm.act("Polling.LFPS",
            self.lfps_tx_idle.eq(1),
            t_polling_lfps.wait.eq(with_timers),
            *([self.ssp_polling.eq(1), self.lfps_tx_polling.eq(self.ssp_fallback)] if ssp else
              [self.lfps_tx_polling.eq(1)]),
            polling_lfps,
        )

        # RxEQ State (7.5.4.4) ---------------------------------------------------------------------
        fsm.act("Polling.RxEQ",
            self.serdes_rx_align.eq(1),
            self.ts_tx_enable.eq(1),
            self.ts_tx_tseq.eq(1),
            If(self.ts_tx_done,
                NextState("Polling.Active")
            ),
        )

        # Active State (7.5.4.5) -------------------------------------------------------------------
        fsm.act("Polling.Active",
            t_active.wait.eq(with_timers),
            self.ts_tx_enable.eq(1),
            self.ts_tx_ts1.eq(1),

            # Latch what we saw from the host (rx_ts1 / rx_ts1_inv / rx_ts2 are pulses).
            NextValue(rx_ts1_seen,     rx_ts1_seen     | self.ts_rx_ts1),
            NextValue(rx_ts1_inv_seen, rx_ts1_inv_seen | self.ts_rx_ts1_inv),
            NextValue(rx_ts2_seen,     rx_ts2_seen     | self.ts_rx_ts2),

            If(t_active.done,
                NextState("Polling.ExitToRxDetect")
            ),

            # 8 consecutive TS1 or TS2 received (7.5.4.8.2): the partner may already be in
            # Polling.Configuration.
            If(self.ts_tx_done & (rx_ts1_seen | rx_ts1_inv_seen | rx_ts2_seen),
                # Polarity (7.5.4.5): TS1_INV evidence (latched during this training attempt)
                # flips the polarity, normal TS1 evidence keeps the current one. On a re-train
                # the previously negotiated polarity is exactly why TS1 decodes normally, so it
                # must be kept (forcing it back to 0 makes every re-training miss TS2 and stall
                # in Polling.Configuration until the next retry).
                If(rx_ts1_inv_seen & ~self.recovery,
                    NextValue(self.serdes_rx_polarity, ~self.serdes_rx_polarity)
                ),
                NextValue(ts2_tx_after, rx_ts2_seen),
                NextState("Polling.Configuration")
            ),
        )

        # Configuration State (7.5.4.6) ------------------------------------------------------------
        fsm.act("Polling.Configuration",
            t_polling_config.wait.eq(with_timers),
            self.ts_tx_enable.eq(1),
            self.ts_tx_ts2.eq(1),
            NextValue(rx_ts2_seen, rx_ts2_seen | self.ts_rx_ts2),
            NextValue(rx_lb_seen,  rx_lb_seen  | self.ts_rx_ts2_loopback),
            If(t_polling_config.done,
                NextState("Polling.ExitToRxDetect")
            ),
            # 8 consecutive TS2 received and 16 TS2 sent after receiving the first of them
            # (7.5.4.9.2): exit at the end of a 16 TS2 burst started after the detection.
            If(self.ts_tx_done,
                NextValue(ts2_tx_after, rx_ts2_seen | self.ts_rx_ts2),
                If(ts2_tx_after,
                    NextState("Polling.Idle")
                )
            )
        )

        # Polling.Idle State (7.5.4.10) ------------------------------------------------------------
        fsm.act("Polling.Idle",
            self.idle_handshake.eq(1), # Idle Symbols + handshake (7.5.4.10).
            self.polling_idle.eq(1),
            self.ts2_decode.eq(1), # Disable Scrambling bit of the received TS2 (7.5.4.10.1).
            t_polling_idle.wait.eq(with_timers),
            If(rx_lb_seen | self.ts_rx_ts2_loopback,
                # Loopback bit in TS2: slave entry, forced (7.5.4.10.2). Checked before the idle
                # handshake: a directed/bit-configured partner must not bounce through U0.
                NextValue(loopback_master, 0),
                NextState("Loopback")
            ).Elif(self.directed_loopback & self.loopback_capable,
                # Directed loopback master (7.5.4.10.2).
                NextValue(loopback_master, 1),
                NextState("Loopback")
            ).Elif(self.ts_rx_ts2_reset & ~self.ds_port,
                # Reset bit in TS2: US to Hot Reset (7.5.4.10.2).
                *goto_hot_reset()
            ).Elif(self.hot_reset_req & self.ds_port,
                # DS directed Hot Reset (7.5.4.10.2).
                *goto_hot_reset()
            ).Elif(self.warm_reset_req & self.ds_port,
                *warm_reset(orig=1)
            ).Elif(self.idle_handshake_done,
                # Idle handshake done (8 Idle received + 16 Idle sent model) -> U0.
                NextState("U0")
            ).Elif(t_polling_idle.done,
                # tPollingIdleTimeout (2ms): Rx.Detect (transient re-train).
                NextState("Polling.ExitToRxDetect")
            )
        )

        # U0 State ---------------------------------------------------------------------------------
        fsm.act("U0",
            self.u0.eq(1),
            self.rx_ready.eq(1),
            self.tx_ready.eq(1),
            # U0 is a TS-receiving state (7.5.6.2 trigger 2: TS1 in U0 -> Recovery, also the
            # directed-Loopback TS1 face): keep RX word re-alignment live. The RXWordAligner
            # re-latches its rotation only while enabled (rx_align); a rotation latched during
            # earlier LFPS/Recovery/SKP-removal traffic would otherwise persist through U0, so every
            # incoming TS1 would mismatch the checker and trigger 2 would be missed.
            self.serdes_rx_align.eq(1),
            t_pm_lc.wait.eq(pm_sent_lgo),
            t_pm_entry.wait.eq(pm_acc_kind != 0),
            t_u0_recovery.wait.eq(with_timers & ~self.link_activity),
            NextValue(self.recovery, 0),
            NextValue(lb_pending, 0),
            NextValue(ux_armed, 0),
            NextValue(rx_lb_seen, 0),
            NextValue(u3_wakeup_pending, 0),
            NextValue(u3_retry_wait, 0),
            NextValue(pm_lgo_fire,  0),
            NextValue(pm_lau_fire,  0),
            NextValue(pm_lxu_fire,  0),
            NextValue(pm_lpma_fire, 0),

            # Warm Reset LFPS detect (6.9: UFP must detect it in any state, responds until DS
            # stops).
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            # Hot Reset: US forced by TS2 Reset bit.
            ).Elif(self.ts_rx_ts2_reset,
                *goto_hot_reset()
            # Hot Reset: DS directed, through Recovery (7.5.6.2): the Reset bit is sent in the TS2
            # of Recovery.Configuration and Hot Reset entered from Recovery.Idle (7.4.2, 7.5.10).
            ).Elif(self.hot_reset_req & self.ds_port,
                *goto_recovery()
            # Real Recovery triggers (7.5.6.2): TS1 detect (trigger 2), tU0RecoveryTimeout (4),
            # directed (3).
            ).Elif(self.ts_rx_ts1, # TS1 received in U0: partner in Recovery (7.5.6.2, trigger 2).
                *goto_recovery()
            ).Elif(t_u0_recovery.done,
                *goto_recovery()
            ).Elif(self.directed_recovery,
                *goto_recovery()
            ).Elif(self.directed_loopback & self.loopback_capable,
                # Directed loopback from U0: via Recovery with TS2 Loopback bit (7.5.11).
                NextValue(lb_pending, 1),
                *goto_recovery()
            ).Elif(self.warm_reset_req & self.ds_port,
                # DS directed Warm Reset: send Warm Reset LFPS burst (6.9).
                *warm_reset(orig=1)
            # PM: accept partner request (UFP shall not reject U3, 7.2.4.2.4).
            ).Elif(self.lgo_u3 & ~pm_sent_lgo & (pm_acc_kind == 0),
                NextValue(pm_acc_kind, 3),
                NextValue(pm_lau_fire, 1)
            ).Elif(self.lgo_u1 & ~pm_sent_lgo & (pm_acc_kind == 0),
                NextValue(pm_acc_kind, 1),
                NextValue(pm_lau_fire, 1)
            ).Elif(self.lgo_u2 & ~pm_sent_lgo & (pm_acc_kind == 0),
                NextValue(pm_acc_kind, 2),
                NextValue(pm_lau_fire, 1)
            # PM concurrency (7.2.4.2.5): LGO sent + LGO received.
            # - DS: rejects the UFP LGO_U1/U2 (LXU), its own request stays outstanding.
            # - UFP: waits for the DS LXU (rejecting its own request), then answers the DS request
            #   (LAU: an upstream port shall not reject U3, 7.2.4.2.4).
            ).Elif(pm_sent_lgo & self.ds_port & (self.lgo_u1 | self.lgo_u2),
                NextValue(pm_lxu_fire, 1)
            ).Elif(pm_sent_lgo & ~self.ds_port & (self.lgo_u1 | self.lgo_u2 | self.lgo_u3),
                If(self.lgo_u3,
                    NextValue(pm_conc_kind, 3)
                ).Elif(self.lgo_u2,
                    NextValue(pm_conc_kind, 2)
                ).Else(
                    NextValue(pm_conc_kind, 1)
                )
            # PM: requester trigger (conditions of 7.2.4.2.2 assumed met by upper layers).
            ).Elif(~pm_sent_lgo & (pm_acc_kind == 0) &
                (self.req_u1 | self.req_u2 | (self.req_u3 & self.ds_port)),
                If(self.req_u3 & self.ds_port,
                    NextValue(pm_kind, 3)
                ).Elif(self.req_u2,
                    NextValue(pm_kind, 2)
                ).Else(
                    NextValue(pm_kind, 1)
                ),
                NextValue(pm_lgo_fire, 1),
                NextValue(pm_sent_lgo, 1)
            ).Elif(pm_sent_lgo,
                # Requester resolution (7.2.4.2.3).
                If(self.lau,
                    NextValue(pm_sent_lgo, 0),
                    NextValue(pm_conc_kind, 0),
                    NextValue(pm_lpma_fire, 1),
                    NextValue(u3_entry_cnt, 0), # entry success breaks the failure streak
                    *goto_ux(pm_kind)
                ).Elif(self.lxu,
                    NextValue(pm_sent_lgo, 0), # rejected: remain in U0
                    NextValue(u3_entry_cnt, 0), # resolved handshake is not a timeout failure
                    # UFP: answer the DS request received while our own LGO was pending (7.2.4.2.5).
                    If(pm_conc_kind != 0,
                        NextValue(pm_acc_kind, pm_conc_kind),
                        NextValue(pm_conc_kind, 0),
                        NextValue(pm_lau_fire, 1)
                    )
                ).Elif(t_pm_lc.done,
                    # PM_LC_TIMER timeout -> Recovery (7.2.4.2.3). U3 entry (pm_kind==3)
                    # counts consecutive failures: the 3rd strike -> eSS.Inactive
                    # (7.2.4.2.4) instead of another Recovery round trip.
                    NextValue(pm_sent_lgo, 0),
                    NextValue(pm_conc_kind, 0),
                    If((pm_kind == 3) & (u3_entry_cnt == 2),
                        NextState("eSS.Inactive")
                    ).Else(
                        If(pm_kind == 3,
                            NextValue(u3_entry_cnt, u3_entry_cnt + 1)
                        ),
                        *goto_recovery()
                    )
                )
            ).Elif(pm_acc_kind != 0,
                # Acceptor resolution: enter Ux on LPMA reception or on PM_ENTRY_TIMER timeout with
                # no LPMA and no TS1 (7.2.4.2.3).
                If(t_pm_entry.done | self.lpma,
                    NextValue(pm_acc_kind, 0),
                    *goto_ux(pm_acc_kind)
                ).Elif(self.ts_rx_ts1,
                    # LAU corrupted case: Recovery before PM_ENTRY timeout (7.2.4.2.3).
                    NextValue(pm_acc_kind, 0),
                    *goto_recovery()
                )
            )
        )

        # U1 State (7.5.7) -------------------------------------------------------------------------
        fsm.act("U1",
            self.lfps_tx_idle.eq(1),
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            t_ux_exit.wait.eq(ux_armed),
            self.u1.eq(1),
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            ).Elif(self.lfps_rx_polling,
                # Simplification: partner restarted training (Rx.Detect absence equivalent).
                NextState("Polling.Entry")
            ).Elif(hs_done_ok,
                # U1 exit handshake success -> both partners to Recovery (6.9.2/7.2.4.2.7).
                *goto_recovery()
            ).Elif(hs_done_err,
                # tNoLFPSResponseTimeout (2ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            ).Elif(with_timers & u2_timeout_done,
                # PORT_U2_TIMEOUT: U1 -> U2 direct degradation (7.2.4.2.3).
                NextState("U2")
            ).Elif(self.ds_port & u1_ping_done,
                # tU1PingTimeout (300ms) without Ping -> Rx.Detect (7.5.7.2).
                NextState("Polling.ExitToRxDetect")
            ).Elif(~hs_run & rx_burst_ok,
                # Responder: partner's single exit burst qualified (6.9.2). hs_rx is pre-latched:
                # the qualified burst IS the partner request evidence.
                *hs_start(mode=1, responder=True),
                # Ux_EXIT_TIMER is only started by the port initiating the exit (7.2.4.2.1).
            ).Elif(~hs_run & ((self.exit_u1_req & (self.ds_port | u1_residency_done))
                              | (self.hot_reset_req & self.ds_port)),
                # U1 exit initiator (UFP only after U1_MIN_RESIDENCY). DS-directed
                # PORT_RESET exits through the same handshake (p189-190); the held
                # request completes the chain later in Recovery.Idle -> Hot Reset.
                *hs_start(mode=1),
                NextValue(ux_armed, 1)
            )
        )

        # U2 State (7.5.8) -------------------------------------------------------------------------
        fsm.act("U2",
            self.lfps_tx_idle.eq(1),
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            t_ux_exit.wait.eq(ux_armed),
            self.u2.eq(1),
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            ).Elif(self.lfps_rx_polling,
                NextState("Polling.Entry") # Simplification: partner restarted training.
            ).Elif(hs_done_ok,
                *goto_recovery()
            ).Elif(hs_done_err,
                NextState("eSS.Inactive")
            ).Elif(~hs_run & rx_burst_ok,
                # Responder: partner's single exit burst qualified (6.9.2), hs_rx pre-latched.
                *hs_start(mode=2, responder=True),
                # Ux_EXIT_TIMER is only started by the port initiating the exit (7.2.4.2.1).
            ).Elif(~hs_run & (self.exit_u2_req | (self.hot_reset_req & self.ds_port)),
                # U2 exit initiator; DS-directed PORT_RESET rides the same
                # handshake (p189-190) and completes in Recovery.Idle -> Hot Reset.
                *hs_start(mode=2),
                NextValue(ux_armed, 1)
            )
        )

        # U3 State (7.5.9) -------------------------------------------------------------------------
        fsm.act("U3",
            self.lfps_tx_idle.eq(1),
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            self.u3.eq(1),
            t_u3_retry.wait.eq(u3_retry_wait),
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            ).Elif(self.lfps_rx_polling,
                NextState("Polling.Entry") # Simplification: partner restarted training.
            ).Elif((self.hot_reset_req | self.warm_reset_req) & self.ds_port,
                # PORT_RESET/BH_PORT_RESET directed in U3 -> Warm Reset
                # (Inband Reset selection, p189-190).
                *warm_reset(orig=1)
            ).Elif(hs_done_ok,
                # U3 wakeup handshake success -> Recovery (7.2.4.2.7).
                NextValue(u3_wakeup_pending, 0),
                NextValue(u3_retry_wait, 0),
                *goto_recovery()
            ).Elif(hs_done_err,
                # Wakeup failure: remain in U3 and retry after tU3WakeupRetryDelay (100ms)
                # (7.2.4.2.7, no failure limit: the 3 failures -> eSS.Inactive rule is for U3
                # entry, 7.2.4.2.4).
                NextValue(u3_retry_wait, 1)
            ).Elif(self.wakeup_u3_req,
                # U3 wakeup initiated by either port (UFP: function remote wakeup, 7.2.4.2.7).
                NextValue(u3_wakeup_pending, 1)
            ).Elif(u3_wakeup_pending & ~hs_run & ~u3_retry_wait,
                # Initiate/retry wakeup (Ux_EXIT_TIMER not applied to U3, 7.2.4.2.1).
                *hs_start(mode=3)
            ).Elif(~hs_run & rx_burst_ok,
                # Respond to the partner wakeup (qualified single burst, hs_rx pre-latched).
                *hs_start(mode=3, responder=True)
            ).Elif(t_u3_retry.done,
                # tU3WakeupRetryDelay (100ms) elapsed: clear the wait so the pending wakeup is
                # re-initiated by the branch above on the next cycle (7.2.4.2.4).
                NextValue(u3_retry_wait, 0)
            )
        )

        # Compliance State (7.5.4.3 entry / 7.5.5) -------------------------------------------------
        fsm.act("Compliance",
            self.lfps_tx_idle.eq(1),
            self.compliance.eq(1),
            self.exit_to_compliance.eq(1),
            If(self.lfps_rx_ping,
                # Ping.LFPS switches test pattern (Simplification: count only).
                NextValue(self.compliance_ping_count, self.compliance_ping_count + 1)
            ),
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            ).Elif(self.warm_reset_req & self.ds_port,
                # Only Warm Reset exits Compliance (7.5.5.2).
                *warm_reset(orig=1)
            )
        )

        # Loopback State (7.5.11) ------------------------------------------------------------------
        fsm.act("Loopback",
            t_ux_exit.wait.eq(ux_armed),
            self.loopback.eq(1),
            If(self.lfps_rx_reset,
                *warm_reset(orig=0)
            ).Elif(self.lfps_rx_polling,
                # Simplification: partner restarted training after failed exit.
                NextState("Polling.ExitToRxDetect")
            ).Elif((self.hot_reset_req | self.warm_reset_req) & self.ds_port,
                # PORT_RESET/BH_PORT_RESET directed in Loopback -> Warm Reset
                # (Inband Reset selection, p189-190); outranks the master exit.
                *warm_reset(orig=1)
            ).Elif(loopback_master & ~self.directed_loopback & ~hs_run,
                # Master exit directed: Loopback exit LFPS (timing of U2 exit, 7.5.11.2).
                *hs_start(mode=2),
                NextState("Loopback.Exit")
            ).Elif(~loopback_master & rx_burst_ok,
                # Slave: exit on the master's qualified Loopback exit LFPS (7.5.11.2);
                # hs_rx pre-latched from the qualified burst.
                *hs_start(mode=2, responder=True),
                NextState("Loopback.Exit")
            )
        )

        # Loopback.Exit State (7.5.11.2) -----------------------------------------------------------
        fsm.act("Loopback.Exit",
            self.lfps_tx_idle.eq(1),
            t_ux_exit.wait.eq(ux_armed),
            self.loopback.eq(1),
            If(hs_done_ok,
                NextState("Polling.ExitToRxDetect")
            ).Elif(hs_done_err,
                # tLoopbackExitTimeout (2ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            )
        )

        # Hot Reset Active State (7.5.12.2) --------------------------------------------------------
        fsm.act("HotReset.Active",
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            self.hot_reset.eq(1),
            t_active.wait.eq(with_timers),
            self.ts_tx_enable.eq(1),
            self.ts_tx_ts2.eq(1),
            NextValue(hr_tx_reset, 1),
            NextValue(hr_seen, hr_seen | self.ts_rx_ts2_reset),
            If((hr_cnt + 1) >= hr_delay,
                # Own reset done: send Reset=0 TS2 (Simplification: symmetric auto-clear).
                NextValue(hr_tx_reset, 0)
            ),
            If(hr_seen & ~self.ts_rx_ts2_reset & ~hr_tx_reset,
                # Both sides saw Reset=0 -> Exit (Simplification: single fall detection).
                NextState("HotReset.Exit")
            ).Elif(t_active.done,
                # tHotResetActiveTimeout (12ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            )
        )

        # Hot Reset Exit State (7.5.12.3) ----------------------------------------------------------
        fsm.act("HotReset.Exit",
            self.idle_handshake.eq(1), # Idle Symbols + handshake (7.5.4.10).
            self.hot_reset.eq(1),
            t_hot_reset_exit.wait.eq(with_timers),
            If(self.idle_handshake_done,
                # Idle handshake -> U0 (7.5.12.3).
                NextState("U0")
            ).Elif(t_hot_reset_exit.done,
                # tHotResetExitTimeout (2ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            )
        )

        # TS2 Reset bit (7.4.2): set in HotReset.Active (until own reset done), and in
        # Recovery.Configuration when the DS is directed to Hot Reset (7.5.10.4). Note: this first
        # reference to Recovery.Configuration fixes its place in the state encoding (ltssm_state).
        in_recovery_config = fsm.ongoing("Recovery.Configuration")
        self.comb += self.ts_tx_ts2_reset.eq(hr_tx_reset |
            (in_recovery_config & self.hot_reset_req & self.ds_port))

        # Warm Reset burst State (6.9, DS originator / UFP responder) ------------------------------
        fsm.act("WarmReset",
            NextValue(polling_lfps_ok, 0),
            self.lfps_tx_idle.eq(1),
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            NextValue(u3_entry_cnt, 0), # reset side effect: PM state cleared
            If(wr_done,
                # Both sides retrain from Rx.Detect (transient) through Polling.
                NextState("Polling.ExitToRxDetect")
            )
        )

        # Recovery Active State (7.5.10.1) ---------------------------------------------------------
        fsm.act("Recovery.Active",
            NextValue(pm_sent_lgo, 0),
            NextValue(pm_acc_kind, 0),
            t_ux_exit.wait.eq(ux_armed),
            t_active.wait.eq(with_timers),
            self.serdes_rx_align.eq(1), # Re-acquire word alignment on the incoming TS1s: the LFPS
                                        # exit burst shifts the RX word phase (Recovery is the only
                                        # TS-receiving path entered after a LFPS burst; the aligner
                                        # re-latches on the K->D boundary of each TS1 set).
            self.ts_tx_enable.eq(1),
            self.ts_tx_ts1.eq(1),

            NextValue(rx_ts1_seen, rx_ts1_seen | self.ts_rx_ts1),
            NextValue(rx_ts2_seen, rx_ts2_seen | self.ts_rx_ts2),
            NextValue(rx_lb_seen,  rx_lb_seen  | self.ts_rx_ts2_loopback),

            If(t_ux_exit.done,
                # Ux_EXIT_TIMER still running in Recovery -> eSS.Inactive (7.2.4.2.1).
                NextState("eSS.Inactive")
            ).Elif(t_active.done,
                # tRecoveryActiveTimeout (12ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            ),
            If(self.ts_tx_done & (rx_ts1_seen | rx_ts2_seen),
                NextValue(ts2_tx_after, rx_ts2_seen),
                NextState("Recovery.Configuration")
            ),
        )

        # Recovery Configuration State (7.5.10.2) --------------------------------------------------
        fsm.act("Recovery.Configuration",
            t_ux_exit.wait.eq(ux_armed),
            t_recovery_config.wait.eq(with_timers),
            self.serdes_rx_align.eq(1), # Keep alignment re-acquisition during the TS2 exchange.
            self.ts_tx_enable.eq(1),
            self.ts_tx_ts2.eq(1),
            NextValue(rx_ts2_seen, rx_ts2_seen | self.ts_rx_ts2),
            NextValue(rx_lb_seen,  rx_lb_seen  | self.ts_rx_ts2_loopback),
            If(t_ux_exit.done,
                NextState("eSS.Inactive")
            ).Elif(t_recovery_config.done,
                # tRecoveryConfigurationTimeout (6ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            ),
            # 8 consecutive TS2 received and 16 TS2 sent after receiving the first of them
            # (7.5.10.4.2): exit at the end of a 16 TS2 burst started after the detection.
            If(self.ts_tx_done,
                NextValue(ts2_tx_after, rx_ts2_seen | self.ts_rx_ts2),
                If(ts2_tx_after,
                    NextState("Recovery.Idle")
                )
            )
        )

        # Recovery Idle State (7.5.10.3) -----------------------------------------------------------
        fsm.act("Recovery.Idle",
            self.ts2_decode.eq(1), # Disable Scrambling bit of the received TS2 (7.5.10.5.1).
            self.idle_handshake.eq(1), # Idle Symbols + handshake (7.5.4.10).
            t_ux_exit.wait.eq(ux_armed),
            t_recovery_idle.wait.eq(with_timers),
            If(t_ux_exit.done,
                NextState("eSS.Inactive")
            ).Elif(self.directed_loopback & self.loopback_capable,
                # Directed loopback master (checked before idle handshake: the partner is being
                # directed into Loopback and must not bounce through U0).
                NextValue(loopback_master, 1),
                NextState("Loopback")
            ).Elif(rx_lb_seen | self.ts_rx_ts2_loopback,
                # Loopback bit in TS2 -> Loopback (slave, forced).
                NextValue(loopback_master, 0),
                NextState("Loopback")
            ).Elif(self.ts_rx_ts2_reset,
                # Reset bit in TS2 -> Hot Reset.
                *goto_hot_reset()
            ).Elif(self.hot_reset_req & self.ds_port,
                # DS-directed Hot Reset (7.5.12 Recovery.Idle entry): completes the
                # U1/U2 directed chain (LFPS Exit -> Recovery -> Hot Reset, p189-190)
                # and must outrank the idle handshake below.
                *goto_hot_reset()
            ).Elif(self.idle_handshake_done,
                # Idle handshake -> U0 (7.5.10.3).
                NextState("U0")
            ).Elif(t_recovery_idle.done,
                # tRecoveryIdleTimeout (2ms) -> eSS.Inactive (Table 7-12).
                NextState("eSS.Inactive")
            )
        )

        # eSS.Inactive State (Table 7-12) ----------------------------------------------------------
        fsm.act("eSS.Inactive",
            self.lfps_tx_idle.eq(1),
            self.ess_inactive.eq(1),
            NextValue(ux_armed, 0),
            NextValue(u3_entry_cnt, 0), # the streak is consumed by going inactive
            t_ess_quiet.wait.eq(with_timers),
            If(t_ess_quiet.done,
                # 12ms quiet -> Rx.Detect (transient re-train).
                NextState("Polling.ExitToRxDetect")
            )
        )

        # Exit to RxDetect (transient, instant re-train) -------------------------------------------
        fsm.act("Polling.ExitToRxDetect",
            self.lfps_tx_idle.eq(1),
            self.exit_to_rx_detect.eq(1),
            t_rx_detect.wait.eq(1),
            If(t_rx_detect.done,
                NextState("Polling.Entry")
            )
        )

        # Warm Reset (6.9, 7.4.2) ------------------------------------------------------------------
        # In every state (except the transient Rx.Detect substates and WarmReset itself), an
        # upstream port shall transition to Rx.Detect upon detection of Warm Reset and a downstream
        # port when directed to issue Warm Reset (exit conditions of 7.5.2 to 7.5.12). Appended last
        # to each state: takes priority over the state's own transitions.
        for state in fsm.actions.keys():
            if state in ["Polling.Entry", "Polling.ExitToRxDetect", "WarmReset"]:
                continue
            fsm.act(state,
                If(self.lfps_rx_reset,
                    *warm_reset(orig=0)
                ).Elif(self.warm_reset_req & self.ds_port,
                    *warm_reset(orig=1)
                )
            )

        # Outputs ----------------------------------------------------------------------------------

        # PM handshake pulses.
        self.comb += [
            self.tx_lgo_u1.eq(pm_lgo_fire & (pm_kind == 1)),
            self.tx_lgo_u2.eq(pm_lgo_fire & (pm_kind == 2)),
            self.tx_lgo_u3.eq(pm_lgo_fire & (pm_kind == 3)),
            self.tx_lau.eq(pm_lau_fire),
            self.tx_lxu.eq(pm_lxu_fire),
            self.tx_lpma.eq(pm_lpma_fire),
        ]

        # LFPS bursts (driven through the LFPSUnit TX mux).
        self.comb += [
            self.lfps_tx_reset.eq(wr_run),
            self.lfps_tx_exit_u1.eq(hs_run & hs_send & (hs_mode == 1)),
            self.lfps_tx_exit_u2.eq(hs_run & hs_send & (hs_mode == 2)),
            self.lfps_tx_wakeup_u3.eq(hs_run & hs_send & (hs_mode == 3)),
        ]

        # State-dependent logic --------------------------------------------------------------------
        # (fsm.ongoing references after the states definitions: the state encoding is unchanged).
        in_u1               = fsm.ongoing("U1")
        in_u2               = fsm.ongoing("U2")
        in_u3               = fsm.ongoing("U3")
        in_loopback         = fsm.ongoing("Loopback")
        in_hot_reset_active = fsm.ongoing("HotReset.Active")
        in_recovery_idle    = fsm.ongoing("Recovery.Idle")
        in_polling_config   = fsm.ongoing("Polling.Configuration")
        in_polling_idle     = fsm.ongoing("Polling.Idle")

        # Partner exit/wakeup request (see rx_burst_ok above): mode-aware (each state listens to its
        # own burst class only), cleared by the handshake start or when leaving the
        # handshake-capable states.
        hs_capable = (in_u1 | in_u2 | in_u3 | in_loopback)
        rx_detect  = Signal()
        self.comb += [
            If(in_u1,
                rx_detect.eq(self.lfps_rx_exit_u1)
            ).Elif(in_u3,
                rx_detect.eq(self.lfps_rx_wakeup_u3)
            ).Else(
                # U2 responder and Loopback slave both listen to U2/Loopback exit bursts.
                rx_detect.eq(self.lfps_rx_exit_u2)
            )
        ]
        # In U1/U2/U3, only a burst started in the state is a request: the burst checkers measure
        # the non-idle duration and still detect the partner's U0 transmission (ex: LPMA, Logical
        # Idle) when the state is entered (U1/U2 entered on LPMA reception), the partner's
        # electrical idle has to be seen first.
        rx_armed = Signal()
        self.sync += [
            If(~hs_capable,
                rx_armed.eq(0)
            ).Elif(~rx_detect,
                rx_armed.eq(1)
            ),
            If(hs_run | ~hs_capable,
                rx_burst_ok.eq(0)
            ).Elif(rx_detect & (rx_armed | in_loopback),
                rx_burst_ok.eq(1)
            )
        ]

        # U1 DS Ping timeout counter (reset on Ping reception).
        self.sync += [
            If(in_u1 & self.ds_port,
                If(self.lfps_rx_ping,
                    u1_ping_cnt.eq(0)
                ).Else(
                    If(~u1_ping_done,
                        u1_ping_cnt.eq(u1_ping_cnt + 1)
                    )
                )
            ).Else(
                u1_ping_cnt.eq(0)
            )
        ]

        # U1 UFP min residency counter.
        self.sync += [
            If(in_u1 & ~self.ds_port,
                If(~u1_residency_done,
                    u1_res_cnt.eq(u1_res_cnt + 1)
                )
            ).Else(
                u1_res_cnt.eq(0)
            )
        ]

        # U2 Inactivity Timeout counter (reset on U1 entry).
        self.sync += [
            If(in_u1,
                u2_tick_cnt.eq(u2_tick_cnt + 1),
                If(u2_tick_cnt == (u2_tick_lim - 1),
                    u2_tick_cnt.eq(0),
                    If(~u2_timeout_done,
                        u2_cnt.eq(u2_cnt + 1)
                    )
                )
            ).Else(
                u2_tick_cnt.eq(0),
                u2_cnt.eq(0),
            )
        ]

        # Hot Reset Active reset-done delay counter.
        self.sync += [
            If(in_hot_reset_active,
                hr_cnt.eq(hr_cnt + 1)
            ).Else(
                hr_cnt.eq(0)
            )
        ]

        self.comb += [
            # Ping.LFPS (UFP in U1, after U1_MIN_RESIDENCY).
            self.lfps_tx_ping.eq(in_u1 & ~self.ds_port & u1_residency_done),
            # Loopback bit of the transmitted TS2 (7.5.4.9.1, 7.5.10.4.1): directed loopback master,
            # in Polling.Configuration or (directed from U0) in Recovery.Configuration/Idle.
            self.ts_tx_ts2_loopback.eq(
                (lb_pending & (in_recovery_config | in_recovery_idle)) |
                (self.directed_loopback & self.loopback_capable &
                    (in_polling_config | in_polling_idle))),
        ]


# SuperSpeedPlus Polling (7.5.4.3-7.5.4.6) ---------------------------------------------------------

class SSPPolling(LiteXModule):
    """SuperSpeedPlus Polling substates (7.5.4.3-7.5.4.6) on the Configuration Lane.

    start (level, LTSSM in Polling.LFPS) runs: Polling.LFPS (SCD1 transmitted, 2 SCD1 sent after a SCD1/
    SCD2 is received) -> Polling.LFPSPlus (SCD2, 2 SCD2 sent after a SCD2 is received, end of SCD) ->
    Polling.PortMatch (PHY Capability LBPMs, the port with the higher capability adjusts to the
    partner's, 4 matched LBPMs sent after 2 consecutive matched received) -> Polling.PortConfig (PHY
    Ready LBPMs, 4 sent after 2 consecutive identical received, the DFP PHY Ready bit 7 de-asserted)
    -> done (level until start is released), x2/gen2 = negotiated lanes/speed (Table 7-14): Gen 1x1
    (x2=0, gen2=0), Gen 1x2 (x2=1), Gen 2x1 (gen2=1), Gen 2x2 (x2=1, gen2=1).

    The PHY Capability LBPM advertises x2_capable (bit 5) and gen2_capable (bit 2, Table 7-13), the
    common capability is the AND of both ports capabilities. On done with gen2, the PHY has to
    switch to 10Gbps (Gen 2 transceiver rate/datapath, Gen2TXDatapath/Gen2RXDatapath) before
    Polling.RxEQ (Gen 2 TSEQ/TS1/TS2 with SYNC/SDS, not yet in USB3LTSSM).

    16 consecutive Polling.LFPS bursts received without SCD (SuperSpeed partner, 7.5.4.3.1) after
    4 SCD1 sent: ss_fallback (level until start is released), the LTSSM continues with the SuperSpeed
    Polling.LFPS handshake. tPollingLBPMLFPSTimeout (12ms) in PortMatch/PortConfig: fail.

    Not implemented: tPollingSCDLFPSTimeout, re-timers presence announcement/RT Config, PortMatch
    re-entry/capability fallback after a training failure (Table 7-15).
    """
    def __init__(self, sys_clk_freq, timer_scale=1, x2_capable=True, gen2_capable=False):
        self.start        = Signal() # i
        self.ds_port      = Signal() # i
        self.x2_capable   = Signal(reset=int(x2_capable))   # i
        self.gen2_capable = Signal(reset=int(gen2_capable)) # i
        self.idle         = Signal() # i: RX electrical idle (Configuration Lane).
        self.tx_lfps      = Signal() # o: LFPS burst (else electrical idle).
        self.tx_active    = Signal() # o: SSP LFPS transmission (tx_lfps drives the transmitter).
        self.done         = Signal() # o
        self.x2           = Signal() # o: Gen X2 (two lanes) negotiated.
        self.gen2         = Signal() # o: Gen 2 (10Gbps) negotiated.
        self.ss_fallback  = Signal() # o
        self.fail         = Signal() # o
        self.state        = Signal(4) # o: (debug).

        # # #

        self.frontend = frontend = LFPSRXFrontEnd()
        self.scd_gen  = scd_gen  = SCDGenerator(sys_clk_freq, timer_scale)
        self.scd_chk  = scd_chk  = SCDChecker(frontend, sys_clk_freq, timer_scale)
        self.lbpm_gen = lbpm_gen = LBPMGenerator(sys_clk_freq, timer_scale)
        self.lbpm_chk = lbpm_chk = LBPMChecker(frontend, sys_clk_freq, timer_scale)
        self.comb += frontend.idle.eq(self.idle)

        # Timeouts.
        lbpm_timeout = rounded_cycles(sys_clk_freq, 12e-3, timer_scale)
        scd_end      = (rounded_cycles(sys_clk_freq,  1e-6, timer_scale) +
                        2*rounded_cycles(sys_clk_freq, 14e-6, timer_scale))
        timer = Signal(32)

        # Received LBPM tracking (consecutive identical/matched).
        rx_last      = Signal(8)
        rx_count     = Signal(2)
        tx_count     = Signal(3)
        scd_rx       = Signal()
        scd_sent_ref = Signal(16)
        plain_count  = Signal(5)
        own_cap      = Signal(8)
        tx_cap       = Signal(8)
        partner_x2   = Signal()
        self.comb += own_cap.eq(lbpm_phy_capability() | (self.gen2_capable << 2) |
            (self.x2_capable << 5))

        self.fsm = fsm = FSM(reset_state="IDLE")
        fsm.act("IDLE",
            NextValue(tx_cap,      own_cap),
            NextValue(scd_rx,      0),
            NextValue(plain_count, 0),
            NextValue(timer,       0),
            NextValue(self.x2,     0),
            NextValue(self.gen2,   0),
            If(self.start,
                NextState("POLLING-LFPS")
            )
        )
        fsm.act("POLLING-LFPS",
            self.tx_active.eq(1),
            scd_gen.enable.eq(1),
            scd_gen.mode.eq(1),
            self.tx_lfps.eq(scd_gen.tx_lfps),
            If((scd_chk.scd1 | scd_chk.scd2) & ~scd_rx,
                NextValue(scd_rx, 1),
                NextValue(scd_sent_ref, scd_gen.count),
            ),
            If(scd_chk.plain,
                If(plain_count != 16, NextValue(plain_count, plain_count + 1))
            ),
            If(scd_rx & (scd_gen.count >= (scd_sent_ref + 2)),
                NextValue(scd_rx, 0),
                NextState("POLLING-LFPSPLUS")
            ).Elif(~scd_rx & (plain_count >= 16) & (scd_gen.count >= 4),
                NextState("SS-FALLBACK")
            ),
            If(~self.start, NextState("IDLE"))
        )
        fsm.act("POLLING-LFPSPLUS",
            self.tx_active.eq(1),
            scd_gen.enable.eq(1),
            scd_gen.mode.eq(2),
            self.tx_lfps.eq(scd_gen.tx_lfps),
            If(scd_chk.scd2 & ~scd_rx,
                NextValue(scd_rx, 1),
                NextValue(scd_sent_ref, scd_gen.count),
            ),
            If(scd_rx & (scd_gen.count >= (scd_sent_ref + 2)),
                NextValue(timer, 0),
                NextState("SCD-END")
            ),
            If(~self.start, NextState("IDLE"))
        )
        fsm.act("SCD-END",
            # End of SCD (Figure 6-36 (c)/(d)): an extra tBurst followed by EI of 2x max tRepeat.
            self.tx_active.eq(1),
            self.tx_lfps.eq(timer < rounded_cycles(sys_clk_freq, 1e-6, timer_scale)),
            NextValue(timer, timer + 1),
            If(timer == scd_end,
                NextValue(timer, 0),
                NextValue(rx_count, 0),
                NextValue(tx_count, 0),
                NextState("POLLING-PORTMATCH")
            ),
            If(~self.start, NextState("IDLE"))
        )
        rx_matched = Signal()
        self.comb += rx_matched.eq(
            ((lbpm_chk.data[0:2] == LBPM_PHY_CAPABILITY) & (lbpm_chk.data == tx_cap)) |
            (lbpm_chk.data[0:2] == LBPM_PHY_READY))
        fsm.act("POLLING-PORTMATCH",
            self.tx_active.eq(1),
            lbpm_gen.enable.eq(1),
            self.tx_lfps.eq(lbpm_gen.tx_lfps),
            NextValue(timer, timer + 1),
            If(lbpm_chk.received,
                If(lbpm_chk.data[0:2] == LBPM_PHY_CAPABILITY,
                    # Highest common capability (x2/Gen 2 when both are capable, Table 7-14).
                    NextValue(tx_cap, lbpm_chk.data & tx_cap),
                    NextValue(partner_x2, lbpm_chk.data[5]),
                ),
                If(rx_matched,
                    If(rx_count != 2, NextValue(rx_count, rx_count + 1))
                ).Else(
                    NextValue(rx_count, 0),
                    NextValue(tx_count, 0),
                )
            ),
            If(lbpm_gen.sent,
                If((lbpm_gen.current == tx_cap) & (rx_count == 2),
                    NextValue(tx_count, tx_count + 1)
                ).Else(
                    NextValue(tx_count, 0)
                )
            ),
            If(tx_count == 4,
                NextValue(self.x2,   tx_cap[5]),
                NextValue(self.gen2, tx_cap[2]),
                NextValue(rx_count, 0),
                NextValue(tx_count, 0),
                NextState("POLLING-PORTCONFIG")
            ),
            If(timer == lbpm_timeout, NextState("FAIL")),
            If(~self.start, NextState("IDLE"))
        )
        tx_ready = Signal(8)
        self.comb += tx_ready.eq(LBPM_PHY_READY | ((self.x2 & self.ds_port) << 6))
        rx_ready_ok = Signal()
        self.comb += rx_ready_ok.eq(
            (lbpm_chk.data[0:2] == LBPM_PHY_READY) &
            (lbpm_chk.data == rx_last) &
            ~lbpm_chk.data[7]) # DFP Config Done (bit 7 de-asserted, x2) / reserved (UFP).
        fsm.act("POLLING-PORTCONFIG",
            self.tx_active.eq(1),
            lbpm_gen.enable.eq(1),
            self.tx_lfps.eq(lbpm_gen.tx_lfps),
            NextValue(timer, timer + 1),
            If(lbpm_chk.received,
                NextValue(rx_last, lbpm_chk.data),
                If(rx_ready_ok,
                    If(rx_count != 2, NextValue(rx_count, rx_count + 1))
                ).Elif(lbpm_chk.data[0:2] == LBPM_PHY_READY,
                    NextValue(rx_count, 1),
                    NextValue(tx_count, 0),
                ).Else(
                    NextValue(rx_count, 0),
                    NextValue(tx_count, 0),
                )
            ),
            If(lbpm_gen.sent & (lbpm_gen.current == tx_ready),
                If(rx_count == 2,
                    NextValue(tx_count, tx_count + 1)
                )
            ),
            If(tx_count == 4,
                NextState("DONE")
            ),
            If(timer == lbpm_timeout, NextState("FAIL")),
            If(~self.start, NextState("IDLE"))
        )
        self.comb += lbpm_gen.data.eq(Mux(fsm.ongoing("POLLING-PORTCONFIG"), tx_ready, tx_cap))
        fsm.act("DONE",
            self.done.eq(1),
            If(~self.start, NextState("IDLE"))
        )
        fsm.act("SS-FALLBACK",
            self.ss_fallback.eq(1),
            If(~self.start, NextState("IDLE"))
        )
        fsm.act("FAIL",
            self.fail.eq(1),
            If(~self.start, NextState("IDLE"))
        )
